@app.route("/approvals/borrow/approve/<int:request_id>", methods=["POST"])
@admin_required
def approve_borrow(request_id):
    conn = get_db()
    cursor = conn.cursor()
    cursor.execute("""
        SELECT br.username, br.item_id, br.quantity, br.status, h.item_name, h.quantity AS h_quantity
        FROM borrow_requests br JOIN hardware h ON h.item_id = br.item_id
        WHERE br.request_id = %s
    """, (request_id,))
    row = cursor.fetchone()

    if not row:
        conn.close()
        flash("Borrow request not found.", "danger")
        return redirect(url_for("approvals"))

    if row["status"] != "pending":
        conn.close()
        flash("This request has already been processed.", "warning")
        return redirect(url_for("approvals"))

    br_qty    = row["quantity"]    # borrow quantity requested
    hw_qty    = row["h_quantity"]  # hardware.quantity available

    if br_qty > hw_qty:
        conn.close()
        flash(f"Not enough inventory for '{row['item_name']}'.", "danger")
        return redirect(url_for("approvals"))

    new_qty = hw_qty - br_qty
    cursor.execute("UPDATE hardware SET quantity = %s, status = %s WHERE item_id = %s",
                   (new_qty, calculate_status(new_qty), row["item_id"]))
    cursor.execute("UPDATE borrow_requests SET status = 'approved' WHERE request_id = %s", (request_id,))
    conn.commit()
    conn.close()
    logger.info(f"Borrow #{request_id} approved.")
    flash(f"Approved: {row['quantity']} x '{row['item_name']}' released to {row['username']}.", "success")
    return redirect(url_for("approvals"))

