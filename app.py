@app.route("/catalog")
@login_required
def catalog():
    conn = get_db()
    cursor = conn.cursor()
    category = request.args.get("category", "All Categories")
    search = request.args.get("search", "")

    query = """
        SELECT h.item_id, h.item_name, h.category, h.quantity, h.unit_price, h.status,
               h.initial_quantity,
               COALESCE((SELECT SUM(qa.added_quantity) FROM quantity_additions qa WHERE qa.item_id = h.item_id), 0) AS total_added,
               COALESCE((SELECT SUM(br.quantity) FROM borrow_requests br WHERE br.item_id = h.item_id AND br.status = 'approved'), 0) AS borrowed
        FROM hardware h
        WHERE 1=1
    """
    params = []
    if category and category != "All Categories":
        query += " AND h.category = %s"
        params.append(category)
    if search:
        query += " AND LOWER(h.item_name) LIKE %s"
        params.append(f"%{search.strip().lower()}%")
    query += " ORDER BY h.item_name ASC"
    cursor.execute(query, params)
    raw_items = cursor.fetchall()

    # Build enriched item list with computed columns
    items = []
    for r in raw_items:
        total_qty = r["initial_quantity"] + r["total_added"]
        available = total_qty - r["borrowed"]
        items.append({
            "item_id":          r["item_id"],
            "item_name":        r["item_name"],
            "category":         r["category"],
            "quantity":         r["quantity"],
            "unit_price":       r["unit_price"],
            "status":           r["status"],
            "initial_quantity": r["initial_quantity"],
            "total_added":      r["total_added"],
            "total_qty":        total_qty,
            "borrowed":         r["borrowed"],
            "available":        available,
        })

    cursor.execute("SELECT DISTINCT category FROM hardware ORDER BY category ASC")
    categories = ["All Categories"] + [r["category"] for r in cursor.fetchall()]

    cursor.execute("SELECT SUM(quantity * unit_price) AS total_value FROM hardware")
    total_value = cursor.fetchone()["total_value"] or 0.0

    # Total Stocks = total quantity of ALL inventory (not filtered by search)
    cursor.execute("SELECT SUM(quantity) AS total_stocks FROM hardware")
    total_stocks = cursor.fetchone()["total_stocks"] or 0

    conn.close()

    cart = session.get("cart", [])
    return render_template("catalog.html",
        items=items, categories=categories, total_value=total_value,
        total_stocks=total_stocks,
        selected_category=category, search=search, cart=cart,
        role=session.get("role"), username=session.get("username")
    )

