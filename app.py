@app.route("/profile", methods=["GET", "POST"])
@login_required
def profile():
    if session.get("role") in PRIVILEGED_ROLES:
        return redirect(url_for("catalog"))

    username = session.get("username")
    conn = get_db()
    cursor = conn.cursor()
    cursor.execute("SELECT username, email, role FROM users WHERE username = %s", (username,))
    user = cursor.fetchone()
    conn.close()

    if request.method == "POST":
        new_password = request.form.get("new_password", "")
        confirm_password = request.form.get("confirm_password", "")

        if new_password != confirm_password:
            flash("Passwords do not match.", "danger")
            return render_template("profile.html", user=user, username=username, role=session.get("role"))

        missing = get_password_requirements(new_password)
        if missing:
            flash("Password is missing: " + ", ".join(missing) + ".", "danger")
            return render_template("profile.html", user=user, username=username, role=session.get("role"))

        hashed_pw = bcrypt.hashpw(new_password.encode("utf-8"), bcrypt.gensalt()).decode("utf-8")
        conn = get_db()
        cursor = conn.cursor()
        cursor.execute("UPDATE users SET password_hash = %s WHERE username = %s", (hashed_pw, username))
        conn.commit()
        conn.close()
        logger.info(f"'{username}' updated their password.")
        flash("Password updated successfully!", "success")
        return redirect(url_for("profile"))

    return render_template("profile.html", user=user, username=username, role=session.get("role"))

