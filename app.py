@app.route("/inventory/export-csv")
@login_required
def export_csv():
    conn = get_db()
    cursor = conn.cursor()
    cursor.execute("""
        SELECT h.item_id, h.item_name, h.category, h.quantity, h.unit_price, h.status,
               h.initial_quantity,
               COALESCE((SELECT SUM(qa.added_quantity) FROM quantity_additions qa WHERE qa.item_id = h.item_id), 0) AS total_added,
               COALESCE((SELECT SUM(br.quantity) FROM borrow_requests br WHERE br.item_id = h.item_id AND br.status = 'approved'), 0) AS borrowed
        FROM hardware h ORDER BY h.item_name ASC
    """)
    rows = cursor.fetchall()
    conn.close()

    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    total = 0.0
    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow(["=================================================="])
    writer.writerow(["CAMPUS HARDWARE INVENTORY MANAGEMENT REPORT"])
    writer.writerow([f"Generated On: {timestamp}"])
    writer.writerow([f"Total Recorded Items: {len(rows)}"])
    writer.writerow(["=================================================="])
    writer.writerow([])
    writer.writerow(["Item ID", "Item Name", "Category", "Initial Qty", "Total Added", "Total Qty", "Borrowed", "Available", "Unit Price", "Total Price", "Status"])

    for r in rows:
        total_qty = r["initial_quantity"] + r["total_added"]
        available = total_qty - r["borrowed"]
        item_total = r["quantity"] * r["unit_price"]
        total += item_total
        writer.writerow([r["item_id"], r["item_name"], r["category"],
                         r["initial_quantity"], r["total_added"], total_qty,
                         r["borrowed"], available,
                         f"${r['unit_price']:,.2f}", f"${item_total:,.2f}", r["status"]])

    writer.writerow([])
    writer.writerow(["", "", "", "", "", "", "", "", "GRAND TOTAL ASSET VALUE:", f"${total:,.2f}", ""])
    output.seek(0)
    logger.info(f"CSV exported by '{session.get('username')}'.")
    return send_file(
        io.BytesIO(output.getvalue().encode("utf-8")),
        mimetype="text/csv",
        as_attachment=True,
        download_name=f"inventory_report_{datetime.now().strftime('%Y%m%d_%H%M%S')}.csv"
    )

